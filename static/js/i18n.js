let currentLang = localStorage.getItem('jahangeer_lang') || 'en';

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('jahangeer_lang', lang);
  
  // Update elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
        if (element.hasAttribute('placeholder')) {
          element.setAttribute('placeholder', translations[lang][key]);
        }
      } else {
        element.textContent = translations[lang][key];
      }
    }
  });

  // Update active status on language selector UI buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('bg-amber-500', 'text-white', 'font-bold');
      btn.classList.remove('bg-gray-100', 'text-gray-700');
    } else {
      btn.classList.remove('bg-amber-500', 'text-white', 'font-bold');
      btn.classList.add('bg-gray-100', 'text-gray-700');
    }
  });

  // Trigger custom event for dynamic components (like cart or products)
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
});
